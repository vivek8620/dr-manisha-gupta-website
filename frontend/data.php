/**
 * Helper: find article by slug
 */
function getArticleBySlug($slug, $articles)
{
    foreach ($articles as $article) {
        if ($article['slug'] === $slug) return $article;
    }
    return null;
}

/**
 * Helper: get related articles (same category, excluding current)
 */
function getRelatedArticles($currentId, $currentCat, $articles, $limit = 3)
{
    $related = [];
    foreach ($articles as $article) {
        if ($article['id'] !== $currentId && $article['cat'] === $currentCat) {
            $related[] = $article;
            if (count($related) >= $limit) break;
        }
    }
    // If not enough, fill with other articles
    if (count($related) < $limit) {
        foreach ($articles as $article) {
            if ($article['id'] !== $currentId && !in_array($article, $related)) {
                $related[] = $article;
                if (count($related) >= $limit) break;
            }
        }
    }
    return $related;
}
